    private void jList1ValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_jList1ValueChanged
                                      
        // Obtener el valor seleccionado de la lista
        String opcion = jList1.getSelectedValue();

        // Evitar errores si no hay nada seleccionado
        if (opcion == null) {
            return;
        }

        switch (opcion) {

            case "Introduccion":
                txtAyuda.setText(
                        "Esta plataforma administra el inventario y la logística de empresas de construcción. Facilita el manejo de materiales, obras y el seguimiento de pedidos, con el fin de asegurar que cada proyecto esté abastecido de manera eficiente y sin contratiempos.\n\n"
                        + "El software centraliza la logística y el stock para constructoras. Te permite coordinar materiales, proyectos y flujo de pedidos para optimizar al máximo los recursos que llegan a cada obra.\n\n"
                        + "Básicamente, el sistema organiza todo lo que entra y sale en una constructora. Controlas materiales, proyectos y pedidos para que el abastecimiento de las construcciones sea rápido y exacto."
                );
                break;

            case "Inicio":
                txtAyuda.setText(
                        "Al iniciar el sistema se muestra el menú principal con las siguientes opciones:\n\n"
                        + "- Sistema: Cerrar sesión o salir.\n" 
                        + "- Mantenimiento: Gestión de Materiales y Proyectos.\n"
                        + "- Operaciones: Registro de Pedidos de materiales.\n"
                        + "- Reportes: Visualización de Stock, Pedidos y Gastos.\n"
                        + "- Ayuda: Guía de usuario."
                );
                break;

            case "Mantenimientos":
                txtAyuda.setText(
                        "En esta sección gestionamos los datos principales:\n\n"
                        + "- Materiales: Insumos (cemento, ladrillos, fierros, etc.).\n"
                        + "- Proyectos: Obras en ejecución o planificadas.\n\n"
                        + "Usted podrá Registrar nuevos, Modificar datos existentes o Eliminarlos si no tienen movimientos asociados."
                );
                break;

            case "Operaciones":
                txtAyuda.setText(
                        "Permite realizar las transacciones diarias:\n\n"
                        + "- Pedido: Se asignan materiales del almacén a un Proyecto específico.\n\n"
                        + "El sistema validará automáticamente si existe stock suficiente antes de confirmar la salida del material."
                );
                break;

            case "Reportes":
                txtAyuda.setText(
                        "Módulo para la generación de informes gerenciales:\n\n"
                        + "- Stock de Materiales: Cantidad actual disponible en almacén.\n"
                        + "- Pedidos por Proyecto: Lista de materiales solicitados por cada obra.\n"
                        + "- Gasto por Proyecto: Valorización monetaria de los materiales consumidos por obra."
                );
                break;

            case "Errores Comunes":
                txtAyuda.setText(
                        "Posibles mensajes de advertencia:\n\n"
                        + "- 'Stock Insuficiente': Intenta pedir más cantidad de la que existe en el almacén.\n"
                        + "- 'Campos Vacíos': Debe llenar todos los datos obligatorios del formulario.\n"
                        + "- 'Datos Duplicados': Intenta registrar un código de material o proyecto que ya existe."
                );
                break;
        }
    
    }//GEN-LAST:event_jList1ValueChanged

