    private void cargarProyectosCombo(){
        cbxElegirProyecto.removeAllItems();
        
        ArrayList<clsProyecto> proyecto = clsProyectoDAO.obtener();
        
        for(int i = 0; i < proyecto.size(); i++){
            clsProyecto clsProye = proyecto.get(i);
            
            if (clsProye != null){
                cbxElegirProyecto.addItem(clsProye.getNombre());
            }
        }
        
    }
    
    private void listadoPorProyecto(){
        DefaultTableModel modelo = new DefaultTableModel();
        
        modelo.addColumn("ID Pedido");
        modelo.addColumn("Codigo Material");
        modelo.addColumn(" Material");
        modelo.addColumn("Unidad");
        modelo.addColumn("Cantidad");
        modelo.addColumn("Precio");
        modelo.addColumn("Fecha");
        modelo.addColumn("SubTotal");
        
        int idProyecto = cbxElegirProyecto.getSelectedIndex() + 1;
        
        ArrayList <clsPedido> datos = clsPedidoDAO.listarPorProyecto(idProyecto);
        for(int i = 0; i < datos.size(); i++){
            clsPedido clsPe = datos.get(i);
            SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");
            String fechaFormateada = sdf.format(clsPe.getFecha());
            ArrayList<clsDetallePedido> detallesPe = clsPe.getDetalles();
            
            for(int j = 0; j < detallesPe.size() ; j++){
                clsDetallePedido detalle = detallesPe.get(j);
                
                modelo.addRow(new Object[]{
                    clsPe.getIdPedido(),
                    detalle.getIdMaterial(),
                    detalle.getNombreMaterial(),
                    detalle.getCategoria(),
                    detalle.getCantidad(),
                    detalle.getCostoUnitario(),
                    fechaFormateada,
                    detalle.getSubtotal()
                });
                
            }
        }
        tblReportePedidos.setModel(modelo);
    }
    
