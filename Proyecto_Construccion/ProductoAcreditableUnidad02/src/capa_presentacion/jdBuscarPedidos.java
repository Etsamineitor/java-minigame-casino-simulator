    private void cargarTabla() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID REGISTRO");
        modelo.addColumn("PROYECTO / SECTOR");
        modelo.addColumn("FECHA");

        clsPedidoDAO.recuperar();
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");

        for (clsPedido p : clsPedidoDAO.listar()) {
            if (!p.isEstado()) {
                continue;
            }

            int idActual = p.getIdPedido();
            boolean existe = false;
            int filaExistente = -1;

            for (int i = 0; i < modelo.getRowCount(); i++) {
                if ((int) modelo.getValueAt(i, 0) == idActual) {
                    existe = true;
                    filaExistente = i;
                    break;
                }
            }

            if (existe) {
                String proyectosActuales = modelo.getValueAt(filaExistente, 1).toString();
                if (!proyectosActuales.contains(p.getNombreProyecto())) {
                    modelo.setValueAt(proyectosActuales + " / " + p.getNombreProyecto(), filaExistente, 1);
                }
            } else {
                modelo.addRow(new Object[]{
                    p.getIdPedido(),
                    p.getNombreProyecto(),
                    sdf.format(p.getFecha())
                });
            }
        }
        tblPedidos.setModel(modelo);
    }

