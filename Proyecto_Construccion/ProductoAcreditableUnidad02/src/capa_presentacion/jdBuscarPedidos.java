    private void txtNombreProductoKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtNombreProductoKeyReleased
        String filtro = txtNombreProducto.getText().toUpperCase();
        DefaultTableModel modelo = (DefaultTableModel) tblPedidos.getModel();
        modelo.setRowCount(0);

        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");

        for (clsPedido p : clsPedidoDAO.listar()) {
            // Filtramos por nombre de proyecto
            if (p.getNombreProyecto().toUpperCase().contains(filtro) && p.isEstado()) {
                modelo.addRow(new Object[]{
                    p.getIdPedido(),
                    p.getNombreProyecto(),
                    sdf.format(p.getFecha())
                });
            }
        }
    }//GEN-LAST:event_txtNombreProductoKeyReleased


    private void tblPedidosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPedidosMouseClicked
        int fila = tblPedidos.getSelectedRow();
        if (fila == -1) {
            return;
        }

        idPedidoSeleccionado
                = Integer.parseInt(tblPedidos.getValueAt(fila, 0).toString());

        int r = JOptionPane.showConfirmDialog(
                this,
                "¿Cargar pedido N° " + idPedidoSeleccionado + "?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION
        );

        if (r == JOptionPane.YES_OPTION) {
            dispose();
        }
    }

