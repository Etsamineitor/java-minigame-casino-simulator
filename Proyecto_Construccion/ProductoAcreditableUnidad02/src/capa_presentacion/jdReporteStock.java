    private void listado() {
        DefaultTableModel modelo = new DefaultTableModel();
        String estado = "";
        modelo.addColumn("Codigo");
        modelo.addColumn("Nombre");
        modelo.addColumn("Unidad");
        modelo.addColumn("Costo");
        modelo.addColumn("Stock");
        modelo.addColumn("Estado");

        ArrayList<clsMaterial> datos = clsMaterialDAO.obtener();
        for (int i = 0; i < datos.size(); i++) {
            clsMaterial clsMate = datos.get(i);
            if (clsMate.isActivo()) {
                estado = "Vigente";
            } else {
                estado = "No vigente";
            }
            modelo.addRow(new Object[]{
                clsMate.getCodigo(),
                clsMate.getNombre(),
                clsMate.getUnidad(),
                clsMate.getCosto(),
                clsMate.getStock(),
                estado
            });
        }

        tblReporteMateriales.setModel(modelo);
    }

