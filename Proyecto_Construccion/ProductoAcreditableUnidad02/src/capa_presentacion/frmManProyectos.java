    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:        
        if (txtCodigo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el código",
                    "Error", JOptionPane.ERROR_MESSAGE);
            posActual = -1;
            return;
        }
        if (!validarCodigoNumerico()) {
            posActual = -1;
            return;
        }

        int codigo = Integer.parseInt(txtCodigo.getText().trim());
        int pos = clsProyectoDAO.posicion(codigo);

        if (pos == -1) {
            JOptionPane.showMessageDialog(this, "Proyecto no encontrado",
                    "Error", JOptionPane.ERROR_MESSAGE);
            posActual = -1;
            return;
        }

        clsProyecto p = clsProyectoDAO.obtener().get(pos);

        txtNombre.setText(p.getNombre());
        txtUbicacion.setText(p.getUbicacion());
        chkVigente.setSelected(p.isEstado());

        posActual = pos;
        modoNuevo = false;

        txtCodigo.setEditable(true);
    }//GEN-LAST:event_btnBuscarActionPerformed

