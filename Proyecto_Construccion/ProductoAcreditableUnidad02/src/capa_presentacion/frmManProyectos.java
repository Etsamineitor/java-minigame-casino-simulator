    private void confirmarSalida() {

        if (datosPendientes) {
            int resp = JOptionPane.showConfirmDialog(
                    this,
                    "Hay datos no guardados.\n¿Desea salir del mantenimiento de Proyectos?",
                    "Advertencia",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE
            );

            if (resp == JOptionPane.YES_OPTION) {
                dispose();
            }
        } else {
            dispose();
        }
    }

    private boolean validarCamposVacios() {
        if (txtCodigo.getText().trim().isEmpty()
                || txtNombre.getText().trim().isEmpty()
                || txtUbicacion.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Faltan datos",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return false;
        }
        return true;
    }

    private boolean validarCodigoNumerico() {
        if (!txtCodigo.getText().trim().matches("\\d+")) {
            JOptionPane.showMessageDialog(this,
                    "El código debe ser numérico",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            txtCodigo.requestFocus();
            return false;
        }
        return true;
    }

    private void limpiar() {
        txtNombre.setText("");
        txtUbicacion.setText("");
        chkVigente.setSelected(true);

        prepararNuevoCodigo();
    }

    private void prepararNuevoCodigo() {
        modoNuevo = true;
        posActual = -1;

        txtCodigo.setText(String.valueOf(clsProyectoDAO.generarCodigo()));
        txtCodigo.setEditable(false);
        btnBuscar.setEnabled(false);

        txtNombre.requestFocus();
    }

    private void activarModoBusqueda() {
        modoNuevo = false;
        posActual = -1;

        txtCodigo.setText("");
        txtCodigo.setEditable(true);
        btnBuscar.setEnabled(true);

        txtNombre.setText("");
        txtUbicacion.setText("");
        chkVigente.setSelected(true);

        txtCodigo.requestFocus();
    }

    private void listado() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("Código");
        modelo.addColumn("Nombre");
        modelo.addColumn("Ubicación");
        modelo.addColumn("Estado");

        for (clsProyecto p : clsProyectoDAO.obtener()) {
            String estado = p.isEstado() ? "Vigente" : "No vigente";
            modelo.addRow(new Object[]{
                p.getIdProyecto(),
                p.getNombre(),
                p.getUbicacion(),
                estado
            });
        }

        tblProyectos.setModel(modelo);
    }

    private void cargarDesdeTabla() {
        int fila = tblProyectos.getSelectedRow();
        if (fila == -1) {
            return;
        }

        activarModoBusqueda();
        txtCodigo.setText(tblProyectos.getValueAt(fila, 0).toString());
        btnBuscarActionPerformed(null);
    }

