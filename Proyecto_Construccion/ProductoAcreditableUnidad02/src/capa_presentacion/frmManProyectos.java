    private void btnNuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNuevoActionPerformed
        // TODO add your handling code here:
        if (!modoNuevo) {
            prepararNuevoCodigo();
            return;
        }

        if (!validarCamposVacios()) {
            return;
        }

        int codigo = Integer.parseInt(txtCodigo.getText().trim());
        String nombre = txtNombre.getText().trim().toUpperCase();
        String ubicacion = txtUbicacion.getText().trim();

        if (clsProyectoDAO.existeNombre(nombre)) {
            JOptionPane.showMessageDialog(this,
                    "Ya existe un proyecto con ese nombre",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            txtNombre.requestFocus();
            return;
        }

        int resp = Funciones.dialogoPregunta("¿Desea registrar este proyecto?");
        if (resp != 0) {
            return;
        }

        clsProyecto nuevo = new clsProyecto(
                codigo,
                nombre,
                ubicacion,
                chkVigente.isSelected()
        );

        clsProyectoDAO.agregar(nuevo);
        clsProyectoDAO.grabar();

        JOptionPane.showMessageDialog(this,
                "Proyecto registrado correctamente",
                "Mensaje",
                JOptionPane.INFORMATION_MESSAGE);

        listado();
        limpiar();
    }//GEN-LAST:event_btnNuevoActionPerformed


    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
        int fila = tblProyectos.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un proyecto para modificar",
                    "Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!validarCamposVacios()) {
            return;
        }

        clsProyecto p = clsProyectoDAO.obtener().get(fila);

        int codigo = Integer.parseInt(txtCodigo.getText().trim());
        String nombre = txtNombre.getText().trim().toUpperCase();
        String ubicacion = txtUbicacion.getText().trim();
        boolean estado = chkVigente.isSelected();

        boolean sinCambios
                = p.getIdProyecto() == codigo
                && p.getNombre().equals(nombre)
                && p.getUbicacion().equals(ubicacion)
                && p.isEstado() == estado;

        if (sinCambios) {
            JOptionPane.showMessageDialog(this,
                    "No has modificado ningún dato",
                    "Aviso",
                    JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        int resp = JOptionPane.showOptionDialog(this,
                "¿Está seguro que desea modificar este proyecto?",
                "Confirmación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                new Object[]{"Sí", "No"},
                "No");

        if (resp != JOptionPane.YES_OPTION) {
            return;
        }

        clsProyecto nuevo = new clsProyecto(
                codigo,
                nombre,
                ubicacion,
                estado
        );

        clsProyectoDAO.modificar(fila, nuevo);
        clsProyectoDAO.grabar();

        JOptionPane.showMessageDialog(this,
                "Proyecto modificado correctamente",
                "Mensaje",
                JOptionPane.INFORMATION_MESSAGE);

        listado();
        limpiar();
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (txtCodigo.getText().trim().isEmpty() || !validarCodigoNumerico()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese un código válido",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        int codigo = Integer.parseInt(txtCodigo.getText().trim());
        int pos = clsProyectoDAO.posicion(codigo);

        if (pos == -1) {
            JOptionPane.showMessageDialog(this,
                    "Proyecto no encontrado",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        int op = Funciones.dialogoPregunta("¿Está seguro de eliminar este proyecto?");
        if (op != 0) {
            return;
        }

        clsProyectoDAO.eliminar(pos);
        clsProyectoDAO.grabar();

        JOptionPane.showMessageDialog(this,
                "Proyecto eliminado",
                "Mensaje",
                JOptionPane.INFORMATION_MESSAGE);

        listado();
        limpiar();
    }//GEN-LAST:event_btnEliminarActionPerformed

