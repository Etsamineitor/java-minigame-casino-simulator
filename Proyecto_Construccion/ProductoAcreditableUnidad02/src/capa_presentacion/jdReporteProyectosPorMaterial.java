    private void cargarMateriales() {
        cbxMaterial.removeAllItems();
        clsMaterialDAO.recuperar();

        for (clsMaterial m : clsMaterialDAO.obtener()) {
            if (m.isActivo()) {
                cbxMaterial.addItem(m.getNombre());
            }
        }
    }

    private void mostrarProyectos() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID Pedido");
        modelo.addColumn("Proyecto");
        modelo.addColumn("Cantidad");
        modelo.addColumn("Precio Unitario");
        modelo.addColumn("Subtotal");

        if (cbxMaterial.getSelectedIndex() == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un material");
            return;
        }

        String nombreMaterial = cbxMaterial.getSelectedItem().toString();

        clsMaterialDAO.recuperar();
        clsMaterial material = clsMaterialDAO.buscarPorNombre(nombreMaterial);

        if (material == null) {
            JOptionPane.showMessageDialog(this, "Material no encontrado");
            return;
        }

        ArrayList<clsPedido> pedidos
                = clsPedidoDAO.listarPedidosQueContienenMaterial(material.getCodigo());

        for (clsPedido p : pedidos) {
            for (clsDetallePedido d : p.getDetalles()) {
                if (d.getIdMaterial() == material.getCodigo()) {
                    modelo.addRow(new Object[]{
                        p.getIdPedido(),
                        p.getNombreProyecto(),
                        d.getCantidad(),
                        d.getCostoUnitario(),
                        d.getSubtotal()
                    });
                }
            }
        }

        tblResultado.setModel(modelo);
    }

