    private void mnuSistemaCerrarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mnuSistemaCerrarSesionActionPerformed
        // 1. Mostramos el aviso de confirmación
    int respuesta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de que desea cerrar la sesión actual?",
            "Confirmar Cierre de Sesión",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.QUESTION_MESSAGE
    );

    // 2. Si el usuario elige "Sí", procedemos al cambio de ventana
    if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
        this.dispose(); // Cierra la ventana actual (Menú)
        
        // Creamos y mostramos el Login nuevamente
        jdinicioSesion login = new jdinicioSesion(null, true);
        login.setLocationRelativeTo(null);
        login.setVisible(true);
    }
    // Si elige "No", no pasa nada y se queda en el Menú
    }//GEN-LAST:event_mnuSistemaCerrarSesionActionPerformed

